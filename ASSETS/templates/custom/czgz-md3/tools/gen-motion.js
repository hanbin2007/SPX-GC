// Generates core/motion.css from Material 3 Expressive spring tokens.
// Usage: node tools/gen-motion.js > core/motion.css
"use strict";

// [name, dampingRatio, stiffness, fallback cubic-bezier]
const SPRINGS = [
  ["sf", 0.6, 800, "cubic-bezier(0.34, 1.45, 0.64, 1)"],  // spatial fast   (expressive)
  ["sd", 0.8, 380, "cubic-bezier(0.22, 1.12, 0.36, 1)"],  // spatial default (expressive)
  ["ss", 0.8, 200, "cubic-bezier(0.22, 1.1, 0.36, 1)"],   // spatial slow    (expressive)
  ["ef", 1.0, 3800, "cubic-bezier(0.2, 0, 0, 1)"],        // effects fast
  ["ed", 1.0, 1600, "cubic-bezier(0.2, 0, 0, 1)"],        // effects default
  ["es", 1.0, 800, "cubic-bezier(0.2, 0, 0, 1)"],         // effects slow
  ["sg", 0.86, 110, "cubic-bezier(0.16, 1.04, 0.3, 1)"]   // gentle (full-screen scenery)
];

function spring(zeta, k) {
  const w0 = Math.sqrt(k);
  const f = zeta < 1
    ? (t) => {
        const wd = w0 * Math.sqrt(1 - zeta * zeta);
        return 1 - Math.exp(-zeta * w0 * t) * (Math.cos(wd * t) + (zeta * w0 / wd) * Math.sin(wd * t));
      }
    : (t) => 1 - Math.exp(-w0 * t) * (1 + w0 * t);
  let settle = 0;
  for (let t = 0; t < 4; t += 0.001) if (Math.abs(1 - f(t)) > 0.002) settle = t;
  settle += 0.001;
  const n = Math.max(28, Math.min(72, Math.round(settle * 90)));
  const pts = [];
  for (let i = 0; i <= n; i += 1) pts.push(i === n ? 1 : +f((settle * i) / n).toFixed(4));
  return { duration: Math.round(settle * 1000), easing: `linear(${pts.join(", ")})` };
}

const lines = [];
const fallback = [];
lines.push("/* Generated by tools/gen-motion.js - Material 3 Expressive spring tokens. */");
lines.push(":root {");
for (const [name, z, k, fb] of SPRINGS) {
  const s = spring(z, k);
  lines.push(`  /* ${name}: dampingRatio ${z}, stiffness ${k} */`);
  lines.push(`  --${name}-d: ${s.duration}ms;`);
  lines.push(`  --${name}-e: ${s.easing};`);
  fallback.push(`    --${name}-e: ${fb};`);
}
lines.push("  --em-acc: cubic-bezier(0.3, 0, 0.8, 0.15);   /* emphasized accelerate */");
lines.push("  --em-dec: cubic-bezier(0.05, 0.7, 0.1, 1);   /* emphasized decelerate */");
lines.push("  --std: cubic-bezier(0.2, 0, 0, 1);           /* standard */");
lines.push("  --std-acc: cubic-bezier(0.3, 0, 1, 1);       /* standard accelerate */");
lines.push("}");
lines.push("");
lines.push("@supports not (transition-timing-function: linear(0, 1)) {");
lines.push("  :root {");
lines.push(...fallback);
lines.push("  }");
lines.push("}");
process.stdout.write(lines.join("\n") + "\n");
